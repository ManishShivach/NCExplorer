@cdo_required
def test_a_comparison_returns_a_mask_and_propagates_missing(series, tmp_path):
    """The claim in every one of the twenty-four descriptions, measured once.

    Values in exactly {0, 1}, and missing in exactly the cells the input had
    missing — not zero there.
    """
    xr = pytest.importorskip("xarray")
    numpy = pytest.importorskip("numpy")

    holes = tmp_path / "holes.nc"
    mask = tmp_path / "mask.nc"
    subprocess.run(["cdo", "setrtomiss,300,400", str(series["series"]),
                    str(holes)], capture_output=True, timeout=120, check=True)
    subprocess.run(["cdo", "gtc,100", str(holes), str(mask)],
                   capture_output=True, timeout=120, check=True)

    with xr.open_dataset(holes, decode_times=False) as source, \
            xr.open_dataset(mask, decode_times=False) as result:
        values = result[list(result.data_vars)[0]].values
        original = source[list(source.data_vars)[0]].values

    assert numpy.isnan(original).any(), "the fixture stopped making holes"
    assert set(numpy.unique(values[~numpy.isnan(values)])) <= {0.0, 1.0}
    # Missing propagates; it does not become 0.
    assert numpy.array_equal(numpy.isnan(values), numpy.isnan(original))


