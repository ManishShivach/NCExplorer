def installed_cdo_version() -> str:
    """The version string of the CDO on PATH — the one the app will run.

    Read from the first line rather than by splitting on "version", because
    ``cdo --version`` goes on to print a compiler version and a library version
    too, and a naive split picks up whichever came first.
    """
    out = subprocess.run(["cdo", "--version"], capture_output=True, text=True,
                         timeout=30)
    first = (out.stdout + out.stderr).splitlines()[0]
    return first.split("version")[1].split()[0]


@cdo_required
def test_the_installed_cdo_is_one_the_caveat_was_measured_against():
    """A version-specific warning outliving its version is a lie with a date.

    If this fails, CDO has moved. Re-run the exit-code checks below: either the
    module is still broken, in which case add the new version to
    ``_YSEASCOMP_BROKEN_IN``, or it was fixed and the caveat must come out.
    Both are deliberate acts, which is the point of failing here rather than
    quietly going on warning about a version nobody is running.
    """
    version = installed_cdo_version()
    assert version in _YSEASCOMP_BROKEN_IN, (
        f"installed CDO is {version}, but the Yseascomp caveat was measured "
        f"against {', '.join(_YSEASCOMP_BROKEN_IN)}; re-verify before trusting it")


