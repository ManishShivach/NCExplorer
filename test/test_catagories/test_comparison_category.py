# --- (3) what the second file is -------------------------------------------

@pytest.mark.parametrize("operator", COMPANION_COMPARISON)
def test_the_second_input_slot_says_what_it_must_hold(operator):
    """``operator_inputs`` is what the model builder captions its slots from.

    Generic "Input 1 / Input 2" is the dangerous kind of true here: two raw
    series into ``ymoneq`` do not fail, they compare the wrong fields.
    """
    stat_module, example_operator, covers, _doc, _purpose = \
        _COMPANION_MODULES[operator_module(operator)]
    slots = operator_inputs(operator)

    assert len(slots) == 2
    assert slots[0].role == "Time series"
    assert stat_module in slots[1].role
    assert covers in slots[1].field
    assert slots[1].recipe == f"{example_operator} {{in1}}"
    # The two files are compared directly, so their units have to agree.
    assert slots[1].units == "same_as_input1"


@pytest.mark.parametrize("operator", COMPANION_COMPARISON)
def test_the_description_names_the_companion_module_and_the_example(operator):
    stat_module, example_operator, _covers, doc_operator, _purpose = \
        _COMPANION_MODULES[operator_module(operator)]
    description = OPERATOR_SCHEMA[operator].description

    assert stat_module in description
    assert f"cdo {doc_operator} infile -{example_operator} infile outfile" \
        in description


@pytest.mark.parametrize("operator", COMPANION_COMPARISON)
def test_the_companion_recipe_is_one_the_builder_can_wire(operator):
    """A single operator over input 1 is what earns the one-click button.

    The button already existed for ``ymonsub``; declaring the recipe is the
    whole of what these twelve needed to get it. See
    ``test_two_input_arithmetic.py`` for the insertion itself.
    """
    from ncexplorer_toolkit.gui.model_builder import _single_operator_recipe

