"""The Comparison section is what CDO says it is, and says what it returns.

Three separate problems, all in the same four modules.

**Where they live.** CDO's Comparison section is four modules and twenty-four
operators. Twelve of them were filed under Statistical values: ``_MODULE_CATEGORY``
named no comparison module, so ``_infer_category`` fell through to the prefix
cascade, where the ("ymon","yseas") branch is tested before any comparison name
and cannot tell ``ymoneq`` from ``ymonmean``. This is the trap that cost the
Arithmetic section thirty-two operators, in the same place, fixed the same way:
name the module, do not patch the cascade.

**What they return.** ``eq``'s description was "Equal." and ``gtc``'s was
"Greater than constant." Neither said the output is a 0/1 mask, and neither said
what happens to missing values — which is the whole content of the formula CDO
prints for each of them, and exactly what distinguishes ``gtc,273.15`` from the
``expr`` a user might write instead. ``expr`` returns 0 where the input is
missing; ``gtc`` returns missing.

**What the second file is.** Ymoncomp and Yseascomp take a *statistics* file as
infile2, not a second series — "Usually infile2 is generated by an operator of
the module Ymonstat" — the same sentence the seven ``*arith`` modules carry, and
the same silent-wrong-answer if it is ignored.

Everything asserted here was measured against the installed CDO 2.6.0, not read
off the documentation; the tests marked ``cdo_required`` re-measure it.
"""

import shutil
import subprocess

import pytest

from ncexplorer_toolkit.core.categories import (
    COMPARISON_OPERATORS, NCExplorerCategory, OPERATOR_CATEGORIES,
    OPERATOR_SCHEMA, _COMPANION_MODULES, _YSEASCOMP_BROKEN_IN,
    menu_operators, operator_inputs, operator_module,
)

cdo_required = pytest.mark.skipif(
    shutil.which("cdo") is None, reason="needs an installed CDO")


#: The CDO 2.6.0 Comparison section, module by module, exactly as the binary
#: reports it. Written out rather than derived from the schema, because a test
#: that asks the schema what the schema contains asserts nothing.
COMPARISON_BY_MODULE = {
    "Comparison of two fields":              "eq ne le lt ge gt",
    "Comparison of a field with a constant": "eqc nec lec ltc gec gtc",
    "Multi-year monthly comparison":         "ymoneq ymonne ymonle ymonlt ymonge ymongt",
    "Multi-year seasonal comparison":        "yseaseq yseasne yseasle yseaslt yseasge yseasgt",
}

COMPARISON = sorted(
    name for names in COMPARISON_BY_MODULE.values() for name in names.split()
)

#: The two modules whose infile2 is a statistics file rather than a series.
COMPANION_COMPARISON = sorted(
    "ymoneq ymonne ymonle ymonlt ymonge ymongt "
    "yseaseq yseasne yseasle yseaslt yseasge yseasgt".split()
)

#: The two-input module that broadcasts. Compc takes one file and the ymon/yseas
#: modules pair fields by month or season, so neither broadcasts.
COMP = "eq ne le lt ge gt".split()

COMPC = "eqc nec lec ltc gec gtc".split()

#: Broken on CDO 2.6.0 — see ``_YSEASCOMP_ABORTS`` in core/categories.py.
YSEASCOMP = "yseaseq yseasne yseasle yseaslt yseasge yseasgt".split()


def test_the_section_is_twenty_four_operators():
    assert len(COMPARISON) == 24
    assert len(set(COMPARISON)) == 24


# --- (1) where they live ----------------------------------------------------

@pytest.mark.parametrize("operator", COMPARISON)
def test_every_comparison_operator_is_filed_under_comparison(operator):
    spec = OPERATOR_SCHEMA.get(operator)
    assert spec is not None, f"{operator} is not in the schema at all"
    assert spec.category is NCExplorerCategory.COMPARISON


def test_comparison_holds_nothing_else():
    """The category is exactly the section — no additions, no omissions."""
    filed = {name for name, spec in OPERATOR_SCHEMA.items()
             if spec.category is NCExplorerCategory.COMPARISON}
    assert filed == set(COMPARISON)


def test_the_two_tables_cannot_disagree():
    """There is one list of the twenty-four, and both tables are built from it.

    The curated menu list held twelve names and a second copy lived inside
    ``_infer_category`` holding fourteen — the twelve plus ``maxc``/``minc``.
    Two lists of one thing disagree eventually, and those two already had.
    """
    assert sorted(COMPARISON_OPERATORS) == COMPARISON
    assert OPERATOR_CATEGORIES[NCExplorerCategory.COMPARISON] == \
        list(COMPARISON_OPERATORS)


@pytest.mark.parametrize("operator", ["maxc", "minc"])
def test_maxc_and_minc_are_arithmetic_in_both_tables(operator):
    """They read like comparisons; CDO files them under Arithc.

    ``maxc`` returns a *value*, the twenty-four return a 0/1 mask, and that is
    the distinction worth keeping. The name set that used to claim them for
    Comparison could never have placed them — the module lookup ran first and
    returned Arithmetic — so the two tables disagreed on paper about an operator
    neither of them decided.
    """
    assert OPERATOR_SCHEMA[operator].category is NCExplorerCategory.ARITHMETIC
    assert operator not in COMPARISON_OPERATORS
    assert operator_module(operator) == "Arithmetic with a constant"


def test_browsing_reaches_the_whole_section():
    """``menu_operators`` is what the menus are built from; nothing may be lost."""
    curated, rest = menu_operators(NCExplorerCategory.COMPARISON)
    assert set(curated) | set(rest) == set(COMPARISON)


@pytest.mark.parametrize("module,names", sorted(COMPARISON_BY_MODULE.items()))
def test_module_membership_matches_the_catalog(module, names):
    for name in names.split():
        assert operator_module(name) == module


@cdo_required
@pytest.mark.parametrize("module", sorted(COMPARISON_BY_MODULE))
def test_the_module_titles_still_agree_with_the_installed_binary(module):
    """The category hangs off four exact strings, so re-probe them.

    ``_MODULE_CATEGORY`` is keyed by the title ``cdo --help`` prints. A title
    that changed upstream would not raise — it would silently stop matching, and
    twelve operators would quietly go back to Statistical values. The catalog
    these titles are read from is generated, and a generated file nobody
    re-checks is a hand-written file with extra steps.
    """
    operator = COMPARISON_BY_MODULE[module].split()[0]
    out = subprocess.run(["cdo", "--help", operator], capture_output=True,
                         text=True, timeout=30)
    assert module in (out.stdout + out.stderr).replace("\n", " ")


# --- (2) what they return ---------------------------------------------------

@pytest.mark.parametrize("operator", COMPARISON)
def test_every_description_states_the_mask_and_the_missing_value_rule(operator):
    """Both halves, for all twenty-four — the mask is useless without the second.

    A user who believes missing becomes 0 will sum the mask and get a count of
    "cells where the comparison failed" that silently includes every cell where
    it could not be asked.
    """
    description = OPERATOR_SCHEMA[operator].description.lower()
    assert "mask" in description
    assert "1 where the comparison holds" in description
    assert "0 where it does not" in description
    # The missing-value branch, in whatever words: it must not be possible to
    # read this description and think missing becomes zero.
    assert "missing" in description
    assert "missing rather than 0" in description


@pytest.mark.parametrize("operator", COMP)
def test_the_comp_module_warns_about_broadcasting(operator):
    """Comp documents the broadcast rule in the same words Arith does.

    The note was gated on ``_MODULE_CATEGORY[module] is ARITHMETIC``, which
    asked whether the operator was arithmetic rather than whether its module
    broadcasts, so these six never showed it.
    """
    description = OPERATOR_SCHEMA[operator].description
    assert "only a single timestep or a single variable" in description
    # The other half of Comp's sentence, which Arith's help does not carry.
    assert "inherits its metadata from infile1 or infile2" in description


