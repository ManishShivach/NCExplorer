@cdo_required
@pytest.mark.parametrize("operator", YSEASCOMP)
def test_the_seasonal_module_really_does_abort(operator, series, tmp_path):
    """The caveat is a measurement, and this is the measurement.

    A non-zero exit from a comparison operator is a real failure, which is why
    these must never be added to the exit-code-tolerant branch ``diff`` uses.
    The exit code is also the *only* signal: the abort leaves a header-only file
    behind, so "did an output file appear?" answers yes for a run that produced
    nothing usable. CDO will not reopen what it just wrote.
    """
    output = tmp_path / f"{operator}.nc"
    out = subprocess.run(
        ["cdo", operator, str(series["series"]), str(series["yseas"]),
         str(output)], capture_output=True, text=True, timeout=120)

    assert out.returncode != 0
    assert "Season MAM already allocated!" in out.stderr

    # The trap this makes concrete: the file exists, and is not data.
    assert output.exists(), "no longer leaves a file — re-word the caveat"
    reopened = subprocess.run(["cdo", "sinfon", str(output)],
                              capture_output=True, text=True, timeout=120)
    assert reopened.returncode != 0
    assert "No data arrays found" in reopened.stdout + reopened.stderr


