    assert ModelNode.from_dict({"id": "n", "kind": OPERATOR,
                                "env": {"CDO_SVD_MODE": "jacobi"}}).env == \
        (("CDO_SVD_MODE", "jacobi"),)
    assert ModelNode.from_dict({"id": "n", "kind": OPERATOR,
                                "env": [["CDO_SVD_MODE", ""]]}).env == ()


