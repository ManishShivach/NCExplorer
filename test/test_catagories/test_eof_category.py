def test_the_cross_run_weight_mode_invariant_is_checked_in_the_graph():
    """The one invariant that spans two runs, checked where both runs exist.

    The Eofcoeff manual states that eofcoeff computes a non-weighted dot
    product, so ``CDO_WEIGHT_MODE`` has to agree across the eof run and the
    eofcoeff run. Set on one and not the other, both commands succeed and the
    coefficients are simply not the coefficients of those EOFs. The model
    builder is the only surface where both are objects at once.
    """
    from ncexplorer_toolkit.core.model import (
        ModelGraph, OPERATOR, SOURCE, WARNING)

    graph = ModelGraph()
    source = graph.add(SOURCE, path="/a.nc")
    eof = graph.add(OPERATOR, operator="eof", parameters=("3",),
                    env=(("CDO_WEIGHT_MODE", "on"),))
    coeff = graph.add(OPERATOR, operator="eofcoeff")
    graph.connect(source.id, 0, eof.id, 0)
    graph.connect(eof.id, 0, coeff.id, 0)
    graph.connect(source.id, 0, coeff.id, 1)

    complaints = [issue for issue in graph.validate()
                  if "CDO_WEIGHT_MODE" in issue.message]
    assert len(complaints) == 1
    assert complaints[0].severity == WARNING
    assert "non-weighted dot product" in complaints[0].message

    # Agreed: no complaint. Both explicitly on…
    graph.update_node(coeff.id, env=(("CDO_WEIGHT_MODE", "on"),))
    assert not [i for i in graph.validate() if "CDO_WEIGHT_MODE" in i.message]

    # …and one left unset against one explicitly off, since unset *is* off.
    # That is the measurement, and treating them as different would fire the
    # warning on the commonest correct graph in the section.
    graph.update_node(eof.id, env=())
    graph.update_node(coeff.id, env=(("CDO_WEIGHT_MODE", "off"),))
    assert not [i for i in graph.validate() if "CDO_WEIGHT_MODE" in i.message]


def test_the_environment_round_trips_through_a_saved_model():
    """A model saved with a weighting and reopened without it computes
    different numbers under the same command line."""
    from ncexplorer_toolkit.core.model import ModelNode, OPERATOR

    node = ModelNode(id="n1", kind=OPERATOR, operator="eof",
                     env=(("CDO_WEIGHT_MODE", "on"),))
