"""The EOFs section says what it needs, what it returns, and when it failed.

Four problems, and the first one is not about the EOFs section at all.

**No surface above the execution layer could run a two-output operator.**
``parse_parameters`` built output rows for ``nout`` 1 and -1 only, ``execute``
refused anything else with "Unsupported operator signature", ``_output_paths``
returned exactly one path for every ``nout != 0``, ``_validate_node`` had no
branch for 2 so a broken graph reached CDO unchallenged, and ``plan_job`` mapped
every output of the keeper step onto the same destination — so a batched ``eof``
collided its eigenvalues and its eigenvectors on one path. That is eleven
operators, not six: ``trend``, ``mrotuv``, ``complextopol``, ``complextorect``
and ``samplegridicon`` were in the same hole, and they come out of it by the
same generic ``nout >= 2`` change. The tests below check ``trend`` beside ``eof``
wherever the claim is about the shape rather than about EOFs, because an
implementation that special-cased eof names would pass the eof half and fail
those.

**The input is assumed to be anomalies and nothing says so.** Measured on 2.6.3:
``cdo eof,3`` over a raw series exits 0, warns about nothing, and returns a
leading mode that is the climatological mean. There is no diagnostic
distinguishing that run from a correct one.

**eofcoeff's two inputs are the ``ifthen`` mask-swap trap in a new place**, and
worse. Both slots captioned "Input 1"/"Input 2"; the files are an eigenvector
file and an anomaly series with the same name, grid and units. Measured: the
right order wrote one file per eigenvector, the swap exited 0 and wrote one per
timestep of the series — 730 files from the same two inputs.

**A run that returns zeros was reported as a success.** The one-sided jacobi
solver can fail to converge, print "Setting Matrix and Eigenvalues to 0 before
return", exit 0, and write an all-zero file. Both warnings go to stderr, and
``stream_notices`` read stdout only, so no surface showed either. That is the
worst failure shape in the section: it looks exactly like a good run.

Everything asserted here was measured against the installed CDO 2.6.3, not read
off the documentation — which is wrong about the obase width, and is checked on
that point below. The tests marked ``cdo_required`` re-measure it.
"""

